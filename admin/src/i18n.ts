type PathValue = string | Record<string, unknown>;

const getByPath = (source: Record<string, unknown>, path: string): PathValue | undefined =>
  path.split('.').reduce<unknown>((acc, key) => {
    if (acc && typeof acc === 'object' && key in acc) {
      return (acc as Record<string, unknown>)[key];
    }

    return undefined;
  }, source) as PathValue | undefined;

export const setAdminLocale = (locale: AdminLocale) => {
  adminLocale.value = locale;
  localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
};

export const translateAdmin = (key: string, params: Record<string, string | number> = {}) => {
  const value = getByPath(messages[adminLocale.value], key) ?? getByPath(messages.ru, key);
  const template = typeof value === 'string' ? value : key;

  return Object.entries(params).reduce(
    (text, [paramKey, paramValue]) => text.split(`{${paramKey}}`).join(String(paramValue)),
    template,
  );
};

export const useAdminI18n = () => {
  const currentLocale = computed({
    get: () => adminLocale.value,
    set: (value: AdminLocale) => setAdminLocale(value),
  });

  return {
    locale: currentLocale,
    locales: adminLocales,
    t: translateAdmin,
  };
};

setAdminLocale(adminLocale.value);
